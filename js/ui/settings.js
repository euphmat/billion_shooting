function updDateLabel(u){ const s = u.d.replace(/-/g, "/"); return u.before ? s + " 以前" : s; }
function renderUpdates(){
  const el = $("updateList"); if (!el) return;
  el.innerHTML = UPDATE_HISTORY.map((u, i) =>
    `<div class="upd-row${i === 0 ? " latest" : ""}">` +
      `<div class="upd-meta"><span class="upd-ver">v${u.v}</span><time class="upd-date" datetime="${u.d}">${updDateLabel(u)}</time></div>` +
      `<div class="upd-text">${u.text ? `<p>${u.text}</p>` : ""}${u.items ? `<ul>${u.items.map(t => `<li>${t}</li>`).join("")}</ul>` : ""}</div>` +
      `${i === 0 ? `<span class="upd-new">NEW</span>` : ""}</div>`).join("");
}
function updateUpdBadge(){
  const b = $("updBadge"); if (b) b.style.display = state.lastSeenUpdate < GAME_VERSION ? "block" : "none";
}
function openUpdates(){
  updOpen = true;
  renderUpdates();
  $("updateOverlay").classList.add("open");
  if (state.lastSeenUpdate < GAME_VERSION){ state.lastSeenUpdate = GAME_VERSION; save(); }
  updateUpdBadge();
}
function closeUpdates(){ updOpen = false; $("updateOverlay").classList.remove("open"); }
